create or replace function public.activate_event_registration(
  requested_event_id text,
  event_payload jsonb
)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if auth.uid() is null then
    raise exception 'Authentication required';
  end if;

  if exists (
    select 1
    from public.event_registrations
    where user_id = auth.uid()
      and event_id = requested_event_id
      and status = 'active'
  ) then
    raise exception 'Already registered for this event';
  end if;

  insert into public.event_registrations (user_id, event_id, payload, status, cancelled_at)
  values (auth.uid(), requested_event_id, event_payload, 'active', null);
end;
$$;

create or replace function public.revoke_event_registration(requested_event_id text)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  update public.event_registrations
  set status = 'revoked', cancelled_at = now()
  where user_id = auth.uid()
    and event_id = requested_event_id
    and status = 'active';
end;
$$;

create or replace function public.validate_event_registration(
  requested_token uuid,
  requested_event_id text
)
returns table (
  event_id text,
  user_id uuid,
  status text,
  registered_at timestamptz
)
language plpgsql
security definer
set search_path = public
as $$
begin
  if auth.uid() is null then
    raise exception 'Authentication required';
  end if;

  if not (
    (auth.jwt() -> 'app_metadata' -> 'roles') ? 'watcher'
    or (auth.jwt() -> 'app_metadata' -> 'roles') ? 'admin'
  ) then
    raise exception 'Watcher access required';
  end if;

  return query
    select registration.event_id,
           registration.user_id,
           registration.status,
           registration.created_at
    from public.event_registrations as registration
    where registration.registration_token = requested_token
      and registration.event_id = requested_event_id
      and registration.status = 'active';
end;
$$;

revoke all on function public.activate_event_registration(text, jsonb) from public;
grant execute on function public.activate_event_registration(text, jsonb) to authenticated;
revoke all on function public.revoke_event_registration(text) from public;
grant execute on function public.revoke_event_registration(text) to authenticated;
revoke all on function public.validate_event_registration(uuid, text) from public;
grant execute on function public.validate_event_registration(uuid, text) to authenticated;

create table if not exists public.role_requests (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  requested_role text not null check (requested_role in ('user', 'admin', 'watcher')),
  status text not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
  created_at timestamptz not null default now(),
  reviewed_at timestamptz,
  unique (user_id, requested_role, status)
);

create table if not exists public.event_check_ins (
  registration_token uuid primary key references public.event_registrations(registration_token) on delete cascade,
  event_id text not null references public.events(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  checked_in_by uuid not null references auth.users(id) on delete restrict,
  checked_in_at timestamptz not null default now()
);

