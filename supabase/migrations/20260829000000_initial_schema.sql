create or replace function public.check_in_event_registration(
  requested_token uuid,
  requested_event_id text
)
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  registration public.event_registrations%rowtype;
  inserted_token uuid;
begin
  if auth.uid() is null then
    raise exception 'Authentication required';
  end if;

  if not (
    (auth.jwt() -> 'app_metadata' -> 'roles') ? 'watcher'
    or (auth.jwt() -> 'app_metadata' -> 'roles') ? 'admin'
  ) then
    raise exception 'Watcher access required';
  end if;

  select * into registration
  from public.event_registrations
  where registration_token = requested_token
    and event_id = requested_event_id
    and status = 'active';

  if not found then
    return 'invalid';
  end if;

  insert into public.event_check_ins (
    registration_token, event_id, user_id, checked_in_by
  ) values (
    registration.registration_token,
    registration.event_id,
    registration.user_id,
    auth.uid()
  ) on conflict (registration_token) do nothing
  returning registration_token into inserted_token;

  if inserted_token is null then
    return 'already_checked_in';
  end if;
  return 'checked_in';
end;
$$;
revoke all on function public.check_in_event_registration(uuid, text) from public;
grant execute on function public.check_in_event_registration(uuid, text) to authenticated;

create or replace function public.load_event_attendance_count(requested_event_id text)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
begin
  if auth.uid() is null then
    raise exception 'Authentication required';
  end if;

  if not (auth.jwt() -> 'app_metadata' -> 'roles') ? 'admin' then
    raise exception 'Admin access required';
  end if;

  if not exists (
    select 1
    from public.events
    where id = requested_event_id
      and creator_id = auth.uid()
  ) then
    raise exception 'Event access denied';
  end if;

  return (
    select count(*)
    from public.event_check_ins
    where event_id = requested_event_id
  );
end;
$$;
revoke all on function public.load_event_attendance_count(text) from public;
grant execute on function public.load_event_attendance_count(text) to authenticated;

create or replace function public.create_role_request()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  requested_role text := new.raw_user_meta_data ->> 'requested_role';
begin
  if requested_role in ('user', 'admin', 'watcher') then
    insert into public.role_requests (user_id, requested_role)
    values (new.id, requested_role)
    on conflict (user_id, requested_role, status) do nothing;
  end if;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created_role_request on auth.users;
create trigger on_auth_user_created_role_request
  after insert on auth.users
  for each row execute function public.create_role_request();

